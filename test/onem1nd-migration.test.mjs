const OLD = 'hivem1nd'; // Compatibility: representative 3.0.0 input, never fresh installation output.
const legacy = value => value.replaceAll('ONEM1ND', OLD.toUpperCase()).replaceAll('onem1nd', OLD);
const base64 = value => Buffer.from(value).toString('base64');
async function put(file, content) { await mkdir(path.dirname(file), { recursive: true }); await writeFile(file, content); return file; }

async function fixture(t, { service = false, folder = OLD } = {}) {
  await mkdir('.work/test-migration', { recursive: true });
  const root = await mkdtemp(path.resolve('.work/test-migration/case-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  const cosmic = path.join(root, 'Cosmic'), homeDir = path.join(root, 'home'), source = path.join(cosmic, folder), destination = path.join(cosmic, 'onem1nd');
  const options = { cosmicPath: cosmic, homeDir, hostname: 'TEST', platform: 'win32', env: {}, kitPath: process.cwd(), protectFile: async () => {} };
  await put(path.join(source, 'user', 'VERSION'), '3.0.0\n');
  const hierarchy = 'project-id: stable-project\nunit-id: stable-unit\n';
  await put(path.join(source, 'user', 'projects', 'project.md'), hierarchy);
  const chat = Buffer.from([0, 255, 42, 14, 7]);
  await put(path.join(source, 'user', 'chats', 'chat.bin'), chat);
  const skill = path.join(homeDir, '.agents', 'skills', 'genesis', 'SKILL.md');
  const skillBytes = `# ${OLD.toUpperCase()}\nRead ${source}/rules.md\n`;
  await put(skill, skillBytes);
  const modified = path.join(homeDir, '.agents', 'skills', 'custom', 'SKILL.md');
  await put(modified, `${OLD} hand-written skill\n`);
  await writeMachineRecord(source, 'TEST', { machine: 'TEST', mind: source, language: 'en', setup: 'done',
    agents: [{ name: 'claude-code', mode: 'auto' }, { name: 'codex', mode: 'auto' }], paths: [], excluded: [],
    managedFiles: { [skill]: hashContent(skillBytes), [modified]: hashContent('older generated bytes') } });
  for (const [client, mcp, hooks] of [
    ['claude', path.join(homeDir, '.claude.json'), path.join(homeDir, '.claude', 'settings.json')],
    ['codex', path.join(homeDir, '.codex', 'config.toml'), path.join(homeDir, '.codex', 'hooks.json')],
  ]) {
    const personal = client === 'codex' ? `# ${OLD} personal comment\nmodel = "personal"\n` : JSON.stringify({ note: `${OLD} personal text`, mcpServers: { personal: { command: 'personal-server' } } });
    const config = buildClientConfig({ client, kitPath: process.cwd(), mindPath: source, nodePath: process.execPath, platform: 'win32', existing: { mcp: personal } });
    const oldMcp = legacy(config.mcp), oldHooks = legacy(config.hooks);
    // Only the brand in generated output changes; personal input is kept byte for byte.
    await put(mcp, oldMcp);
    await put(hooks, oldHooks);
    await put(`${mcp}.relay-owned.json`, JSON.stringify({ client, mindPath: source, entries: [
      { kind: 'mcp', before: base64(personal), after: base64(oldMcp) },
      { kind: 'hooks', before: null, after: base64(oldHooks) },
    ] }));
  }
  const rules = path.join(homeDir, '.codex', 'AGENTS.md');
  await put(rules, `Personal ${OLD} rule\n${OLD.toUpperCase()}: the mind is at ${source}. Read ${path.join(source, 'rules.md')} first, then the role or command asked for.\n`);
  const shimDir = path.join(root, 'bin');
  await put(path.join(shimDir, `${OLD}.cmd`), `@node "%dp0%\\node_modules\\${OLD}\\cli\\index.mjs" %*\n`);
  options.shimDirectories = [shimDir];
  const calls = [], registered = new Map();
  if (service) {
    const oldKey = mindKeyFor(source, options.platform), oldLocal = path.join(cosmic, `${OLD}-service`, oldKey, 'TEST');
    const current = planRegistration({ platform: 'win32', nodePath: process.execPath, cliPath: path.join(process.cwd(), 'cli', 'index.mjs'),
      mindPath: source, workingDirectory: process.cwd(), localDirectory: oldLocal, sid: 'S-1-5-21-123' });
    current.name = legacy(current.name);
    current.installationId = 'existing-installation-id';
    await put(path.join(oldLocal, 'registration.json'), JSON.stringify(ownershipRecord(current)));
    await put(path.join(oldLocal, 'service-task.xml'), Buffer.from(`\uFEFF${current.body}`, 'utf16le'));
    await put(path.join(oldLocal, 'config.json'), JSON.stringify({ mindPath: source, machine: 'TEST', startWithWindows: true,
      origin: { kind: 'folder', path: path.join(cosmic, `${OLD}-origin`, oldKey) }, stagingPath: path.join(oldLocal, 'staging') }));
    await put(path.join(cosmic, `${OLD}-origin`, oldKey, 'encrypted.pack'), chat);
    registered.set(current.name, current);
    options.stopService = async () => { calls.push(['stop']); return { stopped: true }; };
    options.queryRegistration = async plan => registered.has(plan.name) ? { present: true, matchesPlan: true, digest: plan.digest, executable: plan.executable, arguments: plan.arguments } : { present: false };
    options.run = async argv => {
      calls.push(argv);
      if (argv.includes('/Create')) {
        const checkpoint = JSON.parse(await readFile(path.join(cosmic, '.onem1nd-upgrade.json')));
        const plan = checkpoint.registrations[0].plan;
        registered.set(plan.name, plan);
      }
      if (argv.includes('/Delete')) registered.delete(argv[argv.indexOf('/TN') + 1]);
    };
  }
  return { root, source, destination, options, hierarchy, chat, skill, modified, calls, registered, rules };
}

test('3.0.0 migrates data, service, Claude, Codex and ownership twice without losing personal entries', async t => {
  const f = await fixture(t, { service: true });
  const first = await migrate(f.options);
  assert.equal(first.migrated, true);
  const second = await migrate(f.options);
  assert.equal(second.migrated, false);
  assert.equal(await readFile(path.join(f.destination, 'user', 'projects', 'project.md'), 'utf8'), f.hierarchy);
  assert.deepEqual(await readFile(path.join(f.destination, 'user', 'chats', 'chat.bin')), f.chat);
  await assert.rejects(readFile(path.join(f.source, 'user', 'VERSION')), { code: 'ENOENT' });
  const claude = JSON.parse(await readFile(path.join(f.options.homeDir, '.claude.json')));
  assert.equal(claude.note, `${OLD} personal text`);
  assert.deepEqual(claude.mcpServers.personal, { command: 'personal-server' });
  assert.ok(claude.mcpServers['onem1nd-relay']);
  assert.equal(claude.mcpServers[`${OLD}-relay`], undefined);
  assert.ok(claude.mcpServers['onem1nd-relay'].args.includes(f.destination));
  const toml = await readFile(path.join(f.options.homeDir, '.codex', 'config.toml'), 'utf8');
  assert.ok(toml.includes(`# ${OLD} personal comment`));
  assert.ok(parseToml(toml).mcp_servers['onem1nd-relay']);
  assert.equal(parseToml(toml).mcp_servers[`${OLD}-relay`], undefined);
  assert.equal(await readFile(f.modified, 'utf8'), `${OLD} hand-written skill\n`);
  assert.match(await readFile(f.skill, 'utf8'), /ONEM1ND/);
  const { record } = await readMachineRecord(f.destination, 'TEST');
  assert.equal(record.mind, f.destination);
  assert.equal(record.managedFiles[f.skill], hashContent(await readFile(f.skill)));
  assert.equal(record.managedFiles[f.modified], hashContent('older generated bytes'));
  assert.match(await readFile(f.rules, 'utf8'), /^Personal .*\nONEM1ND:/);
  assert.equal(f.registered.size, 1);
  assert.equal([...f.registered.keys()][0].startsWith('ONEM1ND-'), true);
  assert.equal(f.calls.filter(call => call.includes('/Create')).length, 1);
  assert.equal(f.calls.filter(call => call.includes('/Delete')).length, 1);
  const local = path.join(f.options.cosmicPath, 'onem1nd-service', mindKeyFor(f.destination, 'win32'), 'TEST');
  assert.equal(JSON.parse(await readFile(path.join(local, 'registration.json'))).installationId, 'existing-installation-id');
  assert.equal(JSON.parse(await readFile(path.join(local, 'config.json'))).mindPath, f.destination);
  await assert.rejects(readFile(path.join(f.options.shimDirectories[0], `${OLD}.cmd`)), { code: 'ENOENT' });
  for (const client of ['claude', 'codex']) await unconfigureRelayClient({ client, homeDir: f.options.homeDir, env: {}, mindPath: f.destination, protectFile: async () => {} });
  assert.equal(JSON.parse(await readFile(path.join(f.options.homeDir, '.claude.json'))).note, `${OLD} personal text`);
});

test('an interrupted copy resumes before retiring any old file', async t => {
  const f = await fixture(t);
  let interrupted = false;
  await assert.rejects(migrate({ ...f.options, afterCopy: async () => { if (!interrupted) { interrupted = true; throw new Error('interrupted copy'); } } }), /interrupted copy/);
  assert.equal(await readFile(path.join(f.source, 'user', 'VERSION'), 'utf8'), '3.0.0\n');
  await migrate(f.options);
  await migrate(f.options);
  assert.deepEqual(await readFile(path.join(f.destination, 'user', 'chats', 'chat.bin')), f.chat);
});

test('an interrupted configuration transaction replays its saved writes', async t => {
  const f = await fixture(t, { folder: '.m1nd' });
  let interrupted = false;
  await assert.rejects(migrate({ ...f.options, afterWrite: async () => { if (!interrupted) { interrupted = true; throw new Error('interrupted write'); } } }), /interrupted write/);
  await migrate(f.options);
  await migrate(f.options);
  assert.equal((await readMachineRecord(f.destination, 'TEST')).record.managedFiles[f.skill], hashContent(await readFile(f.skill)));
});

test('destination collisions retain the source and the personal destination', async t => {
  const f = await fixture(t);
  const target = path.join(f.destination, 'user', 'VERSION');
  await put(target, 'personal destination');
  await assert.rejects(migrate(f.options), { code: 'MIGRATION_CONFLICT' });
  assert.equal(await readFile(target, 'utf8'), 'personal destination');
  assert.equal(await readFile(path.join(f.source, 'user', 'VERSION'), 'utf8'), '3.0.0\n');
});

test('evolve applies and records the rebrand once from 3.0.0 without a version bump', async t => {
  const f = await fixture(t);
  const options = { ...f.options, mindPath: f.source, pull: false,
    installAgentAssets: async () => ({ conflicts: [], agents: [], baseFiles: [], warnings: [] }) };
  const first = await evolve(options);
  assert.equal(first.completed, true);
  assert.equal(first.fromVersion, '3.0.0');
  assert.equal(first.toVersion, '3.0.0');
  assert.deepEqual(first.migrations, ['3.0.0-onem1nd']);
  const second = await evolve({ ...options, mindPath: f.destination });
  assert.equal(second.completed, true);
  assert.deepEqual(second.migrations, []);
  assert.equal(await readFile(path.join(f.destination, 'user', 'MIGRATIONS'), 'utf8'), '3.0.0-onem1nd\n');
});

test('handwritten hooks inserted before generated groups keep their bytes and ownership remains removable', async t => {
  const f = await fixture(t);
  const file = path.join(f.options.homeDir, '.claude', 'settings.json');
  const document = JSON.parse(await readFile(file));
  const personal = { hooks: [{ type: 'command', command: `echo ${OLD} personal hook` }] };
  document.hooks.Stop.unshift(personal);
  await writeFile(file, JSON.stringify(document));
  await migrate(f.options);
  await migrate(f.options);
  const migrated = JSON.parse(await readFile(file));
  assert.deepEqual(migrated.hooks.Stop[0], personal);
  assert.ok(migrated.hooks.Stop[1].hooks[0].args.includes(f.destination));
  await unconfigureRelayClient({ client: 'claude', homeDir: f.options.homeDir, env: {}, mindPath: f.destination, protectFile: async () => {} });
  assert.deepEqual(JSON.parse(await readFile(file)).hooks.Stop, [personal]);
});

test('retirement verifies empty directories again after an interrupted upgrade', async t => {
  const f = await fixture(t);
  const directory = path.join(f.destination, 'empty-personal-folder');
  await mkdir(path.join(f.source, 'empty-personal-folder'));
  let interrupted = false;
  await assert.rejects(migrate({ ...f.options, afterWrite: async () => {
    if (interrupted) return;
    interrupted = true;
    await rm(directory, { recursive: true });
    throw new Error('interrupted after copy');
  } }), /interrupted after copy/);
  await assert.rejects(migrate(f.options), { code: 'MIGRATION_CONFLICT' });
  assert.equal(await readFile(path.join(f.source, 'user', 'VERSION'), 'utf8'), '3.0.0\n');
  assert.deepEqual(await readdir(path.join(f.source, 'empty-personal-folder')), []);
  await mkdir(directory);
  await migrate(f.options);
  await migrate(f.options);
  assert.deepEqual(await readdir(directory), []);
});
