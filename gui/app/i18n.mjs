const DICTIONARIES = {
  en: Object.fromEntries(Object.entries(COPY).map(([key, value]) => [key, value[0]])),
  es: Object.fromEntries(Object.entries(COPY).map(([key, value]) => [key, value[1]])),
};

export function text(language, key, variables = {}) {
  const dictionary = DICTIONARIES[language] ?? DICTIONARIES.en;
  if (!Object.hasOwn(dictionary, key)) throw new Error(`Unknown copy key: ${key}`);
  return dictionary[key]
    .replace(/(^|[^\p{L}\p{N}_{}/\\-])(mind|mente)(?=$|[^\p{L}\p{N}_{}/\\-])/giu, '$1M1ND')
    .replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? ''));
}

function locale(language) {
  return language === "es" ? "es" : "en";
}

// One formatter per kind and language: building one costs far more than using it.
const FORMATTERS = new Map();

function formatter(kind, language, build) {
  const code = locale(language);
  const key = `${kind}:${code}`;
  let cached = FORMATTERS.get(key);
  if (!cached) {
    cached = build(code);
    FORMATTERS.set(key, cached);
  }
  return cached;
}

function pluralForm(language, count) {
  const number = Number(count);
  const safe = Number.isFinite(number) ? number : 0;
  return formatter("plural", language, (code) => new Intl.PluralRules(code)).select(safe) === "one" ? "One" : "Other";
}

export function formatNumber(language, value) {
  const number = Number(value);
  if (!Number.isFinite(number)) return "";
  return formatter("number", language, (code) => new Intl.NumberFormat(code)).format(number);
}

export function cardinal(language, key, count, variables = {}) {
  const number = Number(count);
  const safe = Number.isFinite(number) ? number : 0;
  return text(language, `${key}${pluralForm(language, safe)}`, {
    ...variables,
    count: formatNumber(language, safe),
  });
}

const WHEN = {
  year: "numeric",
  month: "short",
  day: "numeric",
  hour: "2-digit",
  minute: "2-digit",
  hourCycle: "h23",
  timeZone: "UTC",
};

export function formatWhen(language, value) {
  if (value == null || value === "") return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return String(value);
  return formatter("when", language, (code) => new Intl.DateTimeFormat(code, WHEN)).format(date);
}

const CLOCK = {
  hour: "2-digit",
  minute: "2-digit",
  hourCycle: "h23",
  timeZone: "UTC",
  timeZoneName: "short",
};

export function formatClock(language, value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return formatter("clock", language, (code) => new Intl.DateTimeFormat(code, CLOCK)).format(date);
}

const SHORT_TIME = {
  hour: "2-digit", minute: "2-digit", hourCycle: "h23", timeZone: "UTC",
};

export function formatShortTime(language, value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return formatter("short", language, (code) => new Intl.DateTimeFormat(code, SHORT_TIME)).format(date);
}

export function limitsUsage(language, messages = {}, bytes = {}) {
  const messageForm = pluralForm(language, messages.max ?? 0);
  const byteForm = pluralForm(language, bytes.max ?? 0);
  return text(language, `limitsUsage${messageForm}${byteForm}`, {
    messages: formatNumber(language, messages.used ?? 0),
    max: formatNumber(language, messages.max ?? 0),
    bytes: formatNumber(language, bytes.used ?? 0),
    byteMax: formatNumber(language, bytes.max ?? 0),
  });
}

