export const LANGUAGES = ['en', 'es'];

export function text(language, key, variables = {}) {
  const locale = language === 'es' ? 'es' : 'en';
  const value = COPY[locale][key];
  if (value === undefined) throw new Error(`Unknown setup text: ${key}`);
  return Object.entries(variables).reduce(
    (result, [name, replacement]) => result.replaceAll(`{${name}}`, String(replacement)),
    value.replace(/(^|[^\p{L}\p{N}_{}/\\-])(mind|mente)(?=$|[^\p{L}\p{N}_{}/\\-])/giu, '$1M1ND'),
  );
}

const RELAY_KEYS = { configured: 'relayConfigured', refreshed: 'relayRefreshed', 'already-configured': 'relayAlready', 'not-available': 'relayNotAvailable', failed: 'relayFailed' };

// One line per client for the result of ensureRelayClients.
export function relayLine(language, item) {
  return text(language, RELAY_KEYS[item.status], { client: item.client, reason: item.reason ?? '' });
}

export function option(language, value, labelKey, hintKey) {
  const descriptor = { value, label: text(language, labelKey) };
  if (hintKey) descriptor.hint = text(language, hintKey);
  return descriptor;
}

export function detectLanguage(env = process.env) {
  const locale = env.LC_ALL || env.LC_MESSAGES || env.LANG || Intl.DateTimeFormat().resolvedOptions().locale || 'en';
  return String(locale).toLowerCase().startsWith('es') ? 'es' : 'en';
}
